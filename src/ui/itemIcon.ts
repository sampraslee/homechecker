export function hasItemIcon(catalogItemId: string): boolean {
  return catalogItemId in itemIcons;
}

/** The icon for a catalog Item; an identifier outside the catalog gets a plain box. */
export function itemIcon(catalogItemId: string): LucideIcon {
  return itemIcons[catalogItemId] ?? Box;
}
